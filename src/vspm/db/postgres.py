"""PostgreSQL backend with the same interface as the SQLite `Database`.

Used when VSPM_DATABASE_URL is set (Streamlit Community Cloud: the container's disk
is temporary, so all state - barcodes, labels, print jobs, history - lives in a
persistent cloud PostgreSQL shared by every PC).

The application SQL is written for SQLite (`?` placeholders, `lastrowid`); this
module adapts it:

* `?` -> `%s`, literal `%` -> `%%` (outside quoted strings);
* INSERT into a table with an `id` column gets `RETURNING id` (for `lastrowid`);
* Python booleans are stored as 0/1 (the schema uses INTEGER flags);
* rows can be read by position and by column name, like `sqlite3.Row`;
* write transactions take one transaction-scoped advisory lock, so writers run
  one at a time exactly like SQLite's BEGIN IMMEDIATE. All the read-then-write
  safety checks (one label per row, one pending print job per label, the barcode
  sequence) therefore behave identically on both engines. The load is a handful
  of writes per minute, so serialising writers costs nothing noticeable.
"""

from __future__ import annotations

import re
from contextlib import contextmanager
from typing import Any, Iterator

from vspm.db.database import MIGRATIONS_DIR, DatabaseBase, _split_sql, utcnow

WRITE_LOCK = 0x56535041  # "VSPA": serialises write transactions (like SQLite BEGIN IMMEDIATE)
MIGRATION_LOCK = 0x5653504D  # "VSPM": one instance migrates at a time


class Row(tuple):
    """Tuple that can also be indexed by column name (compatible with sqlite3.Row usage)."""

    def __new__(cls, names: list[str], values):
        r = super().__new__(cls, values)
        r._names = names
        return r

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._names.index(key))
            except ValueError:
                raise IndexError(f"No item with that key: {key}") from None
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._names)


def _row_factory(cursor):
    names = [c.name for c in cursor.description or []]
    return lambda values: Row(names, values)


def translate(sql: str, has_params: bool) -> str:
    """SQLite-style SQL to psycopg: `?` -> `%s` and `%` -> `%%`, outside quoted text."""
    out = []
    quote = None
    for ch in sql:
        if quote:
            if ch == quote:
                quote = None
            out.append("%%" if (ch == "%" and has_params) else ch)
            continue
        if ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%" and has_params:
            out.append("%%")
        else:
            out.append(ch)
    return "".join(out)


def translate_ddl(stmt: str) -> str:
    return re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                  stmt, flags=re.I)


_INSERT_RE = re.compile(r"^\s*INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)", re.I)


def _params(params):
    if isinstance(params, dict):
        return {k: (int(v) if isinstance(v, bool) else v) for k, v in params.items()}
    return tuple(int(v) if isinstance(v, bool) else v for v in params)


class Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid
        self.rowcount = cur.rowcount

    def fetchone(self):
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


class Connection:
    """sqlite3.Connection-like wrapper over a psycopg connection."""

    def __init__(self, raw, id_tables: set[str]):
        self.raw = raw
        self._id_tables = id_tables

    def execute(self, sql: str, params: tuple | dict = ()) -> Cursor:
        has = bool(params)
        q = translate(sql, has)
        m = _INSERT_RE.match(sql)
        returning = bool(m and m.group(1).lower() in self._id_tables and "RETURNING" not in sql.upper())
        if returning:
            q = q.rstrip().rstrip(";") + " RETURNING id"
        cur = self.raw.execute(q, _params(params) if has else None)
        lastrowid = None
        if returning:
            r = cur.fetchone()
            lastrowid = r[0] if r else None
        return Cursor(cur, lastrowid)


_POOLS: dict[str, Any] = {}


def _pool(url: str, min_size: int, max_size: int):
    """One pool per database URL per process (Streamlit reruns and contexts share it)."""
    from psycopg_pool import ConnectionPool

    if url not in _POOLS:
        _POOLS[url] = ConnectionPool(url, min_size=min_size, max_size=max_size, open=True,
                                     kwargs={"autocommit": True, "row_factory": _row_factory},
                                     check=ConnectionPool.check_connection, name="vspm")
    return _POOLS[url]


def close_pools(url_prefix: str = "") -> None:
    for url in [u for u in _POOLS if u.startswith(url_prefix.replace("postgresql+psycopg://", "postgresql://", 1))]:
        _POOLS.pop(url).close()


class PostgresDatabase(DatabaseBase):
    backend = "postgresql"

    def __init__(self, url: str, *, min_size: int = 1, max_size: int = 4):
        self.url = url.replace("postgresql+psycopg://", "postgresql://", 1)
        self.path = "postgresql"
        self.pool = _pool(self.url, min_size, max_size)
        self._id_tables: set[str] = set()
        self.migrate()

    def close(self) -> None:
        close_pools(self.url)

    def _load_id_tables(self, raw) -> None:
        self._id_tables = {r[0] for r in raw.execute(
            "SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema() "
            "AND column_name = 'id'").fetchall()}

    @contextmanager
    def connect(self) -> Iterator[Connection]:
        with self.pool.connection() as raw:
            yield Connection(raw, self._id_tables)

    @contextmanager
    def transaction(self, immediate: bool = True) -> Iterator[Connection]:
        with self.pool.connection() as raw:
            with raw.transaction():
                if immediate:
                    raw.execute("SELECT pg_advisory_xact_lock(%s)", (WRITE_LOCK,))
                yield Connection(raw, self._id_tables)

    def migrate(self) -> list[str]:
        applied: list[str] = []
        with self.pool.connection() as raw:
            raw.execute("SELECT pg_advisory_lock(%s)", (MIGRATION_LOCK,))
            try:
                raw.execute("CREATE TABLE IF NOT EXISTS schema_migrations "
                            "(version TEXT PRIMARY KEY, applied_at TEXT NOT NULL)")
                done = {r[0] for r in raw.execute("SELECT version FROM schema_migrations").fetchall()}
                for f in sorted(MIGRATIONS_DIR.glob("*.sql")):
                    if f.stem in done:
                        continue
                    with raw.transaction():
                        for stmt in _split_sql(f.read_text(encoding="utf-8")):
                            raw.execute(translate_ddl(stmt))
                        raw.execute("INSERT INTO schema_migrations VALUES (%s, %s)", (f.stem, utcnow()))
                    applied.append(f.stem)
                self._load_id_tables(raw)
            finally:
                raw.execute("SELECT pg_advisory_unlock(%s)", (MIGRATION_LOCK,))
        return applied

    def execute(self, sql: str, params: tuple | dict = ()) -> Any:
        with self.transaction() as conn:
            return conn.execute(sql, params).lastrowid
